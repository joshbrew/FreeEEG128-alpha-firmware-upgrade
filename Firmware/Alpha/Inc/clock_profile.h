#ifndef FREEEEG128_CLOCK_PROFILE_H
#define FREEEEG128_CLOCK_PROFILE_H

/* CPU grades keep USB/ADC kernel clocks independent and AHB above USB's 30 MHz
 * minimum. HSE is 8.192 MHz; PLL2 and ADC clocks stay independent. 480 MHz requires silicon rev V; other
 * revisions use 400 MHz instead. Query !INFO for the actual speed/revision.
 */
#ifndef FREEEEG128_CPU_MHZ
#define FREEEEG128_CPU_MHZ 80
#endif

#if FREEEEG128_CPU_MHZ == 40
#define FREEEEG128_CORE_DIVIDER RCC_SYSCLK_DIV2
#define FREEEEG128_AHB_DIVIDER RCC_HCLK_DIV1
#elif FREEEEG128_CPU_MHZ == 80
#define FREEEEG128_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG128_AHB_DIVIDER RCC_HCLK_DIV2
#elif FREEEEG128_CPU_MHZ == 160 || FREEEEG128_CPU_MHZ == 240
#define FREEEEG128_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG128_AHB_DIVIDER RCC_HCLK_DIV4
#elif FREEEEG128_CPU_MHZ == 320 || FREEEEG128_CPU_MHZ == 400 || FREEEEG128_CPU_MHZ == 480
#define FREEEEG128_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG128_AHB_DIVIDER RCC_HCLK_DIV8
#else
#error "Supported FreeEEG128 CPU MHz: 40, 80, 160, 240, 320, 400, 480"
#endif

#if FREEEEG128_CPU_MHZ == 480
#define FREEEEG128_PLL_N (HAL_GetREVID() == REV_ID_V ? 117u : 97u)
#define FREEEEG128_VOLTAGE_SCALE (HAL_GetREVID() == REV_ID_V ? PWR_REGULATOR_VOLTAGE_SCALE0 : PWR_REGULATOR_VOLTAGE_SCALE1)
#else
#define FREEEEG128_PLL_N (FREEEEG128_CPU_MHZ <= 80 ? 19u : (FREEEEG128_CPU_MHZ * 125u / 512u))
#if FREEEEG128_CPU_MHZ <= 160
#define FREEEEG128_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE3
#elif FREEEEG128_CPU_MHZ == 240
#define FREEEEG128_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE2
#else
#define FREEEEG128_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE1
#endif
#endif

/* N + FRAC/8192 = target VCO / 8.192 MHz; P=2. Exact integer MHz. */
#if FREEEEG128_CPU_MHZ == 480
#define FREEEEG128_PLL_FRAC (HAL_GetREVID() == REV_ID_V ? 1536u : 5376u)
#define FREEEEG128_PLL_QR (HAL_GetREVID() == REV_ID_V ? 12u : 10u)
#else
#define FREEEEG128_PLL_FRAC (FREEEEG128_CPU_MHZ <= 80 ? 4352u : ((FREEEEG128_CPU_MHZ * 2000u) % 8192u))
#define FREEEEG128_PLL_QR (FREEEEG128_CPU_MHZ <= 80 ? 2u : FREEEEG128_CPU_MHZ / 40u)
#endif
#if FREEEEG128_CPU_MHZ >= 240
#define FREEEEG128_PLL_VCO RCC_PLL1VCOWIDE
#else
#define FREEEEG128_PLL_VCO RCC_PLL1VCOMEDIUM
#endif
/* Board oscillator U7, shared nominal 8.192 MHz clock; never copy
 * FreeEEG32's 16 MHz Y2 value here. build.py sets HSE_VALUE for HAL and CMSIS. */
#define FREEEEG128_HSE_HZ 8192000u
#if FREEEEG128_CPU_MHZ == 480
#define FREEEEG128_HSI_PLL_N (HAL_GetREVID() == REV_ID_V ? 60u : 50u)
#else
#define FREEEEG128_HSI_PLL_N (FREEEEG128_CPU_MHZ <= 80 ? 10u : FREEEEG128_CPU_MHZ / 8u)
#endif
#define FREEEEG128_HSI_PLL_QR (FREEEEG128_HSI_PLL_N / 5u)

#if FREEEEG128_CPU_MHZ == 240
/* HCLK=60 MHz, VOS2: above the 55 MHz zero-wait-state limit. */
#define FREEEEG128_FLASH_LATENCY FLASH_LATENCY_1
#else
#define FREEEEG128_FLASH_LATENCY FLASH_LATENCY_0
#endif

#endif
